import assert from "node:assert/strict";
import { readFileSync, readdirSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import { capabilityFor, isReferenceOnly, parseAsmaEntries, slugForCode } from "./lib/batteries-dna-catalog.mjs";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const read = (path) => JSON.parse(readFileSync(resolve(root, path), "utf8"));
const sourcePath = "packages/batteries-base/src/data/asmaul-husna.ts";
const source = readFileSync(resolve(root, sourcePath), "utf8");
const sourceEntries = parseAsmaEntries(source);
const catalog = read("modules/batteries-dna/catalog.json");
const ajv = new Ajv2020({ allErrors: true, strict: true });
const schema = read("schemas/batteries-dna-catalog.schema.json");
const validateCatalog = ajv.compile(schema);
assert.equal(validateCatalog(catalog), true, `catalog JSON Schema errors: ${JSON.stringify(validateCatalog.errors)}`);
assert.equal(catalog.registryId, "BATTERIES_DNA_ASMA_99");
assert.equal(catalog.source.editorialStatus, "DRAFT_REVIEW");
assert.ok(catalog.source.references.length >= 3);
assert.match(catalog.source.listBasis, /not presented as the hadith's own enumerated list/i);
assert.equal(catalog.authorityGranted, false);
assert.equal(catalog.runtimeEnabled, false);
assert.equal(sourceEntries.length, 99);
assert.equal(catalog.records.length, 99);
assert.equal(new Set(catalog.records.map((item) => item.id)).size, 99);
assert.equal(new Set(catalog.records.map((item) => item.code)).size, 99);
assert.equal(new Set(catalog.records.map((item) => item.lexiconCode)).size, 99);
assert.equal(new Set(catalog.records.map((item) => item.slug)).size, 99);
assert.equal(catalog.records.filter((item) => item.capability).length, 91);
assert.equal(new Set(catalog.records.map((item) => item.capability).filter(Boolean)).size, 91);
const packageFolders = readdirSync(resolve(root, "packages"), { withFileTypes: true }).filter((entry) => entry.isDirectory() && entry.name.startsWith("batteries-dna-"));
assert.equal(packageFolders.length, 0, "DNA records must live only in the registry, not generated workspace packages");
for (const path of ["packages/batteries-dna-fusion", "config/batteries-dna-fusion.json", "schemas/batteries-dna-fusion.schema.json", "schemas/batteries-dna-manifest.schema.json", "apps/api/src/dna-fusion.ts"]) {
  assert.throws(() => readFileSync(resolve(root, path)), { code: "ENOENT" }, `obsolete fusion/package artifact remains: ${path}`);
}
for (let index = 0; index < 99; index += 1) {
  const expected = sourceEntries[index];
  const item = catalog.records[index];
  assert.equal(item.number, index + 1);
  assert.equal(item.slug, slugForCode(expected.code));
  assert.equal(item.id, `dna-${slugForCode(expected.code)}`);
  assert.equal(item.lexiconCode, expected.code);
  assert.equal(item.arabic, expected.arabic);
  assert.equal(item.transliteration, expected.transliteration);
  assert.equal(item.label, expected.label);
  assert.equal(item.attribute, expected.attribute);
  assert.equal(item.domain, expected.domain);
  assert.equal(item.capability, capabilityFor(expected));
  assert.equal(item.recordType, isReferenceOnly(expected.code) ? "reference_only" : "bounded_project_mapping");
  assert.equal(item.status, "DRAFT_REVIEW");
  assert.equal(item.authorityGranted, false);
  assert.equal(item.runtimeEnabled, false);
}
const invalidReferenceOnly = structuredClone(catalog.records.find((item) => item.recordType === "reference_only"));
invalidReferenceOnly.capability = "forbidden-software-capability";
assert.equal(validateCatalog({ ...catalog, records: catalog.records.map((item) => item.id === invalidReferenceOnly.id ? invalidReferenceOnly : item) }), false);
const registry = await import(`${pathToFileURL(resolve(root, "modules/batteries-dna/index.mjs")).href}?validation=${Date.now()}`);
assert.equal(registry.listBatteriesDna().length, 99);
assert.equal(registry.getBatteriesDna("basir")?.id, "dna-basir");
assert.equal(registry.getBatteriesDna("bashir")?.id, "dna-basir");
assert.equal(registry.getBatteriesDna("@empire/batteries-dna-muhaymin")?.lexiconCode, "muhaymin");
assert.equal(registry.getBatteriesDna("majid")?.slug, "majid");
assert.equal(registry.getBatteriesDna("majid2")?.slug, "maajid");
assert.equal(registry.getBatteriesDna("not-a-lexicon-code"), undefined);
assert.ok(Object.isFrozen(registry.getBatteriesDna("bashir")?.limitations));
assert.equal(read("apps/api/package.json").dependencies["@empire/batteries-dna"], "workspace:*");
assert.equal(read("packages/batteries-world-monitor/package.json").dependencies["@empire/batteries-dna"], "workspace:*");
console.log("PASS: 99 source-linked DNA records validate in one registry; generated packages and fusion preload are absent.");
